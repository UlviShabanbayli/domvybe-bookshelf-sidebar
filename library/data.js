/** flatten for search and routing */
export function prepare(course) {
  let n = 0;
  course.lessons = [];
  course.chapters = course.chapters.map(([title, lessons], ci) => ({
    title, index: ci + 1,
    lessons: lessons.map((l) => {
      const slug = l.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      const lesson = { ...l, id: `${course.id}/${slug}`, slug, n: ++n, chapter: ci + 1, course: course.id };
      course.lessons.push(lesson);
      return lesson;
    }),
  }));
  return course;
}
